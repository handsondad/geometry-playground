import asyncio
import hashlib
import json
import subprocess
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parents[1]
VOICES = {
    "nian": ("zh-CN-YunxiaNeural", "+0%"),
    "dad": ("zh-CN-YunxiNeural", "-5%"),
}

NODE_COLLECT = r"""
import { halls } from './src/catalog.js';
import { hubChats, hallChats, geometryWiki, geometryTalks } from './src/geometry-story-data.js';
import { labTalks } from './src/lab-talks.js';

const items = [];
const add = (who, text) => {
  const clean = String(text ?? '').trim();
  if (clean) items.push({ who, text: clean });
};

for (const [n, d] of hubChats) { add('nian', n); add('dad', d); }
for (const [n, d] of Object.values(hallChats)) { add('nian', n); add('dad', d); }
for (const w of geometryWiki) {
  add('dad', `${w.scientist}的故事：${w.title}。${w.story} ${w.homeLab}`);
}
for (const t of geometryTalks) {
  for (const turn of t.turns) { add('nian', turn.nian); add('dad', turn.dad); }
  add('nian', t.wrap);
}
for (const turns of Object.values(labTalks)) {
  for (const turn of turns) { add('nian', turn.nian); add('dad', turn.dad); }
}
for (const hall of halls) {
  for (const l of hall.lessons) {
    add('nian', `太棒啦！我搞懂「${l.name}」的秘密啦！`);
    add('dad', l.idea);
  }
}
add('dad', '先别急着选，再看看画板或点「演示这轮」试试看！');

console.log(JSON.stringify(items));
"""


async def generate():
    raw = subprocess.check_output(
        ["node", "--input-type=module", "-e", NODE_COLLECT],
        cwd=ROOT,
        encoding="utf-8",
    )
    items = json.loads(raw)
    unique = {}
    for item in items:
        key = f"{item['who']}|{item['text']}"
        if key not in unique:
            digest = hashlib.sha256(key.encode("utf-8")).hexdigest()[:12]
            unique[key] = (item["who"], item["text"], digest)

    clips_dir = ROOT / "public" / "voice" / "clips"
    clips_dir.mkdir(parents=True, exist_ok=True)

    slots = asyncio.Semaphore(4)
    generated = 0

    async def record(key, who, text, digest):
        nonlocal generated
        dest = clips_dir / f"{digest}.mp3"
        if dest.exists() and dest.stat().st_size > 1024:
            return
        tmp = dest.with_suffix(".tmp")
        voice, rate = VOICES[who]
        async with slots:
            for attempt in range(3):
                try:
                    await edge_tts.Communicate(text, voice, rate=rate).save(tmp)
                    tmp.replace(dest)
                    generated += 1
                    print(f"[{generated}] {dest.name} ({who})", flush=True)
                    return
                except Exception:
                    tmp.unlink(missing_ok=True)
                    if attempt == 2:
                        raise
                    await asyncio.sleep(2 ** attempt)

    await asyncio.gather(*(record(k, w, t, d) for k, (w, t, d) in unique.items()))

    manifest = {k: d for k, (_, _, d) in unique.items()}
    manifest_js = ROOT / "src" / "voice-manifest.js"
    manifest_js.write_text(
        "// Auto-generated by tools/generate-all-voice.py\n"
        f"export const voiceManifest = {json.dumps(manifest, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"Done. Total unique clips: {len(manifest)}, newly generated: {generated}.")


if __name__ == "__main__":
    asyncio.run(generate())
